const CATALOGS = { en: EN, vi: VI };
let activeLocale = "en";

export function normalizeLocale(value) {
  const raw = String(value ?? "").trim().toLowerCase();
  if (!raw) return undefined;
  if (raw === "en" || raw.startsWith("en-") || raw.startsWith("en_")) return "en";
  if (raw === "vi" || raw.startsWith("vi-") || raw.startsWith("vi_")) return "vi";
  return undefined;
}

export function setLocale(value) {
  const locale = normalizeLocale(value);
  if (!locale) throw new Error(EN["language.invalid"].replace("{locale}", String(value ?? "")));
  activeLocale = locale;
  return locale;
}

export function getLocale() { return activeLocale; }

export function getIntlLocale() {
  return SUPPORTED_LOCALES.find(item => item.id === activeLocale)?.intl ?? "en-US";
}

export function localeLabel(locale = activeLocale) {
  const id = normalizeLocale(locale) ?? "en";
  return id === "vi" ? t("language.vietnamese") : t("language.english");
}

export function t(key, vars = {}) {
  const template = CATALOGS[activeLocale]?.[key] ?? EN[key] ?? key;
  return String(template).replace(/\{([A-Za-z0-9_]+)\}/g, (_, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : `{${name}}`
  );
}
